// ── metamorphic (29119-4): เขียนวันเดียวกันต่างแบบ ผลต้องเท่ากัน ──────────────────────────────────────
describe("parseThaiDate — วันเดียวกันเขียนต่างแบบได้ ISO เดียวกัน", () => {
  const pad = (n: number) => String(n).padStart(2, "0");

  // วันตัวแทน: ขอบล่าง/บนของช่วงปี · 29 ก.พ. (กฎ 400 ปี และ 4 ปี) · วันนี้ของไฟล์ · สิ้นเดือน 30 วัน · สิ้นปี
  it.each(["1900-01-01", "2000-02-29", "2024-02-29", "2026-09-28", "2027-04-30", "2027-12-31", "2200-12-31"])(
    "%s: 3 ตัวคั่น × พ.ศ./ค.ศ. × เติม 0 หรือไม่ · yyyy-mm-dd ทั้งสองปี · มีช่องว่างรอบนอก",
    (iso) => {
      const [y, m, d] = iso.split("-").map(Number) as [number, number, number];
      const spellings = [iso, `${y + 543}-${pad(m)}-${pad(d)}`];
      for (const year of [y, y + 543]) {
        for (const sep of ["/", "-", "."]) {
          spellings.push(`${d}${sep}${m}${sep}${year}`, `${pad(d)}${sep}${pad(m)}${sep}${year}`);
        }
      }
      const all = [...spellings, ...spellings.map((s) => ` \t${s}\n `)];
      expect(all.map((s) => parseThaiDate(s))).toStrictEqual(all.map(() => iso));
    },
  );

  // ผล ISO เป็นจุดตรึง: ปี ค.ศ. 1900–2200 น้อยกว่า 2400 จึงไม่ถูกลบ 543 ซ้ำ — ป้อนผลกลับเข้าไปได้ค่าเดิม
  it.each([
    ["31/12/2570", "2027-12-31"],
    ["1/1/2443", "1900-01-01"],
    ["29.02.2567", "2024-02-29"],
    ["2743-12-31", "2200-12-31"],
  ])("%s → %s แล้วป้อนผลกลับได้ค่าเดิม", (input, iso) => {
    expect(parseThaiDate(input)).toBe(iso);
    expect(parseThaiDate(iso)).toBe(iso);
  });
});

