import Decimal from "decimal.js";
import { describe, expect, it } from "vitest";
import { bahtText, taxBranchLabel, thaiDate, thaiDateShort } from "./thai";

describe("bahtText — จำนวนเงินเป็นตัวอักษร", () => {
  it("ใบจริง RC6909-0010: 20,030.00 → สองหมื่นสามสิบบาทถ้วน", () => {
    expect(bahtText("20030.00")).toBe("สองหมื่นสามสิบบาทถ้วน");
  });

  // ชุดเดียวกับ Django core BahtTextTest.test_edge_cases + กรณีเพิ่ม
  it.each([
    ["0", "ศูนย์บาทถ้วน"],
    ["1", "หนึ่งบาทถ้วน"],
    ["10", "สิบบาทถ้วน"],
    ["11", "สิบเอ็ดบาทถ้วน"],
    ["20", "ยี่สิบบาทถ้วน"],
    ["21", "ยี่สิบเอ็ดบาทถ้วน"],
    ["100", "หนึ่งร้อยบาทถ้วน"],
    ["101", "หนึ่งร้อยเอ็ดบาทถ้วน"],
    ["110", "หนึ่งร้อยสิบบาทถ้วน"],
    ["111", "หนึ่งร้อยสิบเอ็ดบาทถ้วน"],
    ["1001", "หนึ่งพันเอ็ดบาทถ้วน"],
    ["25150", "สองหมื่นห้าพันหนึ่งร้อยห้าสิบบาทถ้วน"],
    ["1000000", "หนึ่งล้านบาทถ้วน"],
    ["1000001", "หนึ่งล้านเอ็ดบาทถ้วน"],
    ["1000010", "หนึ่งล้านสิบบาทถ้วน"],
    ["11000000", "สิบเอ็ดล้านบาทถ้วน"],
    ["21000021", "ยี่สิบเอ็ดล้านยี่สิบเอ็ดบาทถ้วน"],
    ["101000000", "หนึ่งร้อยเอ็ดล้านบาทถ้วน"],
    ["1,234,567.89", "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์"],
    ["3418.09", "สามพันสี่ร้อยสิบแปดบาทเก้าสตางค์"],
    ["11.11", "สิบเอ็ดบาทสิบเอ็ดสตางค์"],
    ["0.50", "ศูนย์บาทห้าสิบสตางค์"],
    ["0.01", "ศูนย์บาทหนึ่งสตางค์"],
    ["0.21", "ศูนย์บาทยี่สิบเอ็ดสตางค์"],
    ["-5", "ลบห้าบาทถ้วน"],
  ])("%s → %s", (amount, want) => {
    expect(bahtText(amount)).toBe(want);
  });

  it("ยอดสูงสุดของ numeric(14,2) อ่านครบทุกหลัก", () => {
    expect(bahtText("999999999999.99")).toBe(
      "เก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าล้านเก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทเก้าสิบเก้าสตางค์",
    );
  });

  it("ปัดครึ่งขึ้นแบบ decimal ไม่ใช่ float (1.005 ใน float = 1.00499…)", () => {
    expect(bahtText("1.005")).toBe("หนึ่งบาทหนึ่งสตางค์");
    expect(bahtText("0.004")).toBe("ศูนย์บาทถ้วน");
    expect(bahtText("-0.004")).toBe("ศูนย์บาทถ้วน");
  });

  it("รับ Decimal ได้", () => {
    expect(bahtText(new Decimal("20030"))).toBe("สองหมื่นสามสิบบาทถ้วน");
  });

  it.each(["", "abc", "12x", "NaN", "Infinity"])("ไม่ใช่ตัวเลข (%s) → throw ไม่คืนข้อความว่าง", (bad) => {
    expect(() => bahtText(bad)).toThrow();
  });
});

describe("วันที่ พ.ศ.", () => {
  it("ใบจริง: 2026-09-02 → 2 กันยายน 2569", () => {
    expect(thaiDate("2026-09-02")).toBe("2 กันยายน 2569");
  });

  it("ทุกเดือนสะกดถูก", () => {
    expect(thaiDate("2026-01-31")).toBe("31 มกราคม 2569");
    expect(thaiDate("2024-02-29")).toBe("29 กุมภาพันธ์ 2567");
    expect(thaiDate("2026-07-01")).toBe("1 กรกฎาคม 2569");
    expect(thaiDate("2026-11-15")).toBe("15 พฤศจิกายน 2569");
    expect(thaiDate("2026-12-31")).toBe("31 ธันวาคม 2569");
  });

  it("ISO datetime ใช้ส่วนวันที่ตามที่เขียน ไม่เลื่อนเขตเวลา", () => {
    expect(thaiDate("2026-09-28T23:30:00+07:00")).toBe("28 กันยายน 2569");
  });

  it("แบบย่อ", () => {
    expect(thaiDateShort("2026-09-02")).toBe("2 ก.ย. 2569");
    expect(thaiDateShort("2026-05-10")).toBe("10 พ.ค. 2569");
  });

  it.each(["", "2/9/2569", "2026-9-2", "2026-02-30", "2026-13-01", "วันนี้"])("ไม่ใช่วันจริง (%s) → throw", (bad) => {
    expect(() => thaiDate(bad)).toThrow();
  });
});

describe("taxBranchLabel — ป้ายสาขาตามสรรพากร", () => {
  it("00000 = สำนักงานใหญ่ (ระบบเดิมพิมพ์ '(สำนักงานใหญ่)')", () => {
    expect(taxBranchLabel("00000")).toBe("สำนักงานใหญ่");
  });

  it("สาขาอื่นพิมพ์รหัส 5 หลักเต็ม", () => {
    expect(taxBranchLabel("00001")).toBe("สาขาที่ 00001");
    expect(taxBranchLabel(" 00012 ")).toBe("สาขาที่ 00012");
  });

  it("ไม่มีรหัส → null (ไม่พิมพ์ป้าย)", () => {
    expect(taxBranchLabel(null)).toBeNull();
    expect(taxBranchLabel(undefined)).toBeNull();
    expect(taxBranchLabel("  ")).toBeNull();
  });

  it.each(["1", "0001", "000001", "A0001"])("ไม่ใช่ 5 หลัก (%s) → throw ไม่เดา", (bad) => {
    expect(() => taxBranchLabel(bad)).toThrow();
  });
});
