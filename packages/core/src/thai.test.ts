// ── ด่าน coverage: ค่าขอบของการปัดก่อนอ่าน · เพดาน numeric(14,2) ทั้งสองฝั่ง · ข้อความ error ตรงตัว ──────────────
// ค่าที่คาดคิดมือ: ปัด HALF_UP 2 ตำแหน่ง (สเปก §8) ก่อน แล้วอ่านตามหลักเดียวกับตาราง Django BahtTextTest (ใบจริง RC6909-0010)
// ReceiptDataError เทียบทั้งชนิดและข้อความตรงตัว — เอกสารภาษีต้องบอกได้ว่าข้อมูลช่องไหนเสีย
const expectReceiptDataError = (run: () => unknown, message: string) => {
  expect(run).toThrow(ReceiptDataError);
  expect(run).toThrow(new ReceiptDataError(message));
};

describe("bahtText — ปัดก่อนอ่าน: หลักที่ถูกตัด …4/…5/…6 · ทดเข้าหลักบาท · ติดลบ (BVA · EP)", () => {
  it.each([
    ["1.004", "หนึ่งบาทถ้วน"], // …4 → 1.00 ลง
    ["1.006", "หนึ่งบาทหนึ่งสตางค์"], // …6 → 1.01 ขึ้น (…5 อยู่ในเทสต์เดิม: 1.005)
    ["1.025", "หนึ่งบาทสามสตางค์"], // เสมอหลังเลขคู่ → 1.03 (HALF_EVEN ได้ 1.02 = หนึ่งบาทสองสตางค์)
    ["1.994", "หนึ่งบาทเก้าสิบเก้าสตางค์"], // 1.99
    ["1.995", "สองบาทถ้วน"], // ทดเข้าหลักบาท 2.00 → สตางค์ 00 จึงเป็น "ถ้วน"
    ["20029.995", "สองหมื่นสามสิบบาทถ้วน"], // ทดข้ามหลักจนได้ยอดใบจริง 20,030.00
    ["-0.005", "ลบศูนย์บาทหนึ่งสตางค์"], // เสมอ → หนีศูนย์ −0.01 ยังเป็นลบ (HALF_CEIL ได้ 0.00 ไม่มีคำว่าลบ)
    ["-20030", "ลบสองหมื่นสามสิบบาทถ้วน"],
  ])("%s → %s", (amount, want) => {
    expect(bahtText(amount)).toBe(want);
  });
});

describe("bahtText — เพดาน numeric(14,2) ตรวจหลังปัด ทั้งฝั่งบวกและลบ (BVA) · ข้อความ error ตรงตัว", () => {
  // 999,999,999,999 = (เก้าแสน…เก้า)ล้าน(เก้าแสน…เก้า) · สตางค์ 99
  const MAX_TEXT =
    "เก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าล้านเก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทเก้าสิบเก้าสตางค์";

  it.each([
    ["999999999999.994", MAX_TEXT], // ปัดแล้ว = เพดานพอดี → อ่านได้
    ["-999999999999.99", `ลบ${MAX_TEXT}`], // เพดานฝั่งลบพอดี
    ["-999999999999.994", `ลบ${MAX_TEXT}`],
  ])("%s → อ่านได้ครบทุกหลัก", (amount, want) => {
    expect(bahtText(amount)).toBe(want);
  });

  it.each(["999999999999.995", "-999999999999.995", "1000000000000.00"])(
    "%s → ปัดแล้วเกินเพดาน → ReceiptDataError พร้อมค่าที่ส่งมา",
    (amount) => {
      expectReceiptDataError(() => bahtText(amount), `จำนวนเงินเกิน 999,999,999,999.99 (numeric(14,2)): "${amount}"`);
    },
  );

  it.each(["", "abc", "NaN"])("ไม่ใช่ตัวเลข %j → ReceiptDataError ข้อความตรงตัว", (bad) => {
    expectReceiptDataError(() => bahtText(bad), `จำนวนเงินไม่ใช่ตัวเลข: "${bad}"`);
  });
});

describe("thaiDate / thaiDateShort — ปีอธิกสุรทินแบบ 100/400 ปีในช่วง 2000–2200 (BVA) · ข้อความ error ตรงตัว", () => {
  it.each([
    ["2000-02-29", "29 กุมภาพันธ์ 2543", "29 ก.พ. 2543"], // 2000 หาร 400 ลงตัว → อธิกสุรทิน · 2000 + 543
    ["2024-02-29", "29 กุมภาพันธ์ 2567", "29 ก.พ. 2567"],
    ["2200-02-28", "28 กุมภาพันธ์ 2743", "28 ก.พ. 2743"], // ปีสุดท้ายของช่วง
  ])("%s → %s · %s", (iso, full, short) => {
    expect(thaiDate(iso)).toBe(full);
    expect(thaiDateShort(iso)).toBe(short);
  });

  it.each([
    "2100-02-29", // หาร 100 ลงตัวแต่ไม่ลงตัว 400 → ไม่ใช่อธิกสุรทิน
    "2200-02-29",
    "2023-02-29",
    "2026-04-31", // เดือน 30 วัน
    "2026-06-31",
  ])("%s ไม่มีจริงในปฏิทิน → ReceiptDataError ข้อความตรงตัว", (bad) => {
    const message = `วันที่ต้องเป็น ค.ศ. YYYY-MM-DD ปี 2000–2200 และเป็นวันจริง: "${bad}"`;
    expectReceiptDataError(() => thaiDate(bad), message);
    expectReceiptDataError(() => thaiDateShort(bad), message);
  });
});

describe("taxBranchLabel — ตัดช่องว่างหัวท้ายก่อนตรวจ · ข้อความ error ตรงตัว (EP)", () => {
  it.each([
    ["\t00000\n", "สำนักงานใหญ่"],
    ["99999", "สาขาที่ 99999"], // รหัส 5 หลักค่าสูงสุด
  ])("%j → %s", (code, label) => {
    expect(taxBranchLabel(code)).toBe(label);
  });

  it.each([
    [" 0001 ", "0001"], // ข้อความ error แสดงค่าที่ตัดช่องว่างแล้ว
    ["๐๐๐๐๑", "๐๐๐๐๑"], // เลขไทยไม่ใช่รหัสสาขาของสรรพากร
    ["0000-1", "0000-1"],
    ["00 001", "00 001"], // ช่องว่างข้างในไม่ตัดให้
  ])("%j → ReceiptDataError ไม่เดารหัส", (code, shown) => {
    expectReceiptDataError(() => taxBranchLabel(code), `รหัสสาขาต้องเป็นตัวเลข 5 หลัก: "${shown}"`);
  });
});
