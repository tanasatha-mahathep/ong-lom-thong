describe("maskNationalId — R13 · CLAUDE.md กฎ 7: เห็นเฉพาะหลักแรกและ 3 หลักท้าย", () => {
  it.each([
    ["ติดกัน", "8765432109564", "8 XXXX XXXXX 56 4"],
    ["เว้นวรรคแบบหน้าบัตร", "8 7654 32109 56 4", "8 XXXX XXXXX 56 4"],
    ["ขีดแบบหน้าบัตร", "8-7654-32109-56-4", "8 XXXX XXXXX 56 4"],
    ["หลักตรวจเป็น 0 (Σ = 364 → r = 1)", "1234567890180", "1 XXXX XXXXX 18 0"],
    ["checksum ผิด (ควรลงท้าย 4) ก็ยังมาสก์ตามรูปแบบ", "8765432109565", "8 XXXX XXXXX 56 5"],
  ])("รูปแบบ 13 หลัก · %s: %s", (_label, input, masked) => {
    expect(maskNationalId(input)).toBe(masked);
  });

  it("110 ค่า 13 หลัก (11 prefix × หลักตรวจ 0–9 ทั้งถูกและผิด) เห็นเลข 4 หลักพอดี และ JSON ไม่มีเลข 13 หลักติดกัน", () => {
    const ids = RESIDUES.flatMap(([, prefix]) => DIGITS.map((c) => prefix + c));
    expect(ids).toHaveLength(110);
    for (const id of ids) {
      const masked = maskNationalId(id);
      expect(masked, id).toMatch(/^\d XXXX XXXXX \d\d \d$/);
      expect(masked.replace(/\D/g, ""), id).toBe(id.slice(0, 1) + id.slice(10)); // หลักแรก + 3 หลักท้ายเท่านั้น
    }
    // กฎเดียวกับเทสต์ API: regex บน JSON ทั้งก้อนต้องไม่เจอเลข 13 หลักติดกัน
    expect(JSON.stringify(ids.map((id) => ({ national_id_masked: maskNationalId(id) })))).not.toMatch(/\d{13}/);
  });

  it("ไม่ใช่รูปแบบ 13 หลัก → X ยาวเท่าความยาวหลังตัดตัวคั่น ไม่ใช่ความยาวดิบ (อย่างน้อย 1)", () => {
    expect(maskNationalId("1 2345 67890 12")).toBe("X".repeat(12)); // ดิบ 15 ตัว หลังตัด 12
    expect(maskNationalId(" - ")).toBe("X"); // ดิบ 3 ตัว หลังตัด 0 → ขั้นต่ำ 1
  });
});
