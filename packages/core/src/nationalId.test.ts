describe("ตัวคั่น — ตัดทิ้งเฉพาะช่องว่างทุกชนิด (\\s) กับขีด ASCII (EP)", () => {
  const GROUPS = ["1", "2345", "67890", "12", "1"]; // 1234567890121 แบ่งกลุ่มแบบหน้าบัตร 1-4-5-2-1 · ต่างกันแค่ตัวคั่น

  it.each([
    ["ช่องว่างแบบหน้าบัตร", GROUPS.join(" ")],
    ["ขีดแบบหน้าบัตร", GROUPS.join("-")],
    ["แท็บ", GROUPS.join("\t")],
    ["NBSP U+00A0 (คัดลอกจากหน้าเว็บ)", GROUPS.join("\u00a0")],
    ["ขึ้นบรรทัดใหม่หัวท้าย", "\n1234567890121\n"],
    ["CRLF ต่อท้าย (คัดลอกจาก Excel)", "1234567890121\r\n"],
    ["ปนกัน ซ้ำ และไม่ตรงกลุ่มหน้าบัตร", " -1 23-45--678 90 1-21- "],
  ])("ตัดทิ้ง: %s", (_label, input) => {
    expect(normalizeNationalId(input)).toBe("1234567890121");
    expect(isValidNationalId(input)).toBe(true);
    expect(maskNationalId(input)).toBe("1 XXXX XXXXX 12 1");
  });

  it.each([
    ["จุด", GROUPS.join(".")],
    ["ขีดล่าง", GROUPS.join("_")],
    ["en dash U+2013", GROUPS.join("\u2013")],
  ])("ไม่ตัด → ไม่ผ่าน และมาสก์ปิดทั้งหมด: %s", (_label, input) => {
    expect(normalizeNationalId(input)).toBe(input);
    expect(isValidNationalId(input)).toBe(false);
    expect(maskNationalId(input)).toBe("X".repeat(17)); // เลข 13 + ตัวคั่น 4 = 17 ตัว
  });
});

