/**
 * ตัวเลขขั้นต่ำที่ถือว่าคำค้นคือเลขบัตรประชาชน — 12 หลักแรกกำหนดหลักที่ 13 (check digit) ได้ครบ
 * จึงเท่ากับทั้งเลข ไม่ต้องรอให้พิมพ์ครบ 13
 */
const NATIONAL_ID_DIGITS = 12;

/**
 * คำค้นนี้มีเลขบัตรประชาชนเต็มอยู่ไหม — นับตัวเลข ≥ 12 ตัวหลังตัดทุกอย่างที่ไม่ใช่ 0-9
 * นับแบบเดียวกับ API (`replace(/\D/g, "")` แล้ว LIKE %ตัวเลข%): ชื่อปน · ขีดคั่นชนิดใดก็ได้ · จุด ·
 * อักขระที่มองไม่เห็น · เลขเกิน 13 หลัก ก็ยังหาลูกค้าเจอ จึงต้องถือว่าเป็นเลขบัตรทั้งหมด
 * เบอร์โทร (10–11 หลัก) และเลขที่บิล (RC6910-0001) ไม่เข้าข่าย — ยังลง URL ได้ตามเดิม
 *
 * หน้าค้นทุกหน้า (ค้นบิล · ค้นลูกค้า) ค้นด้วยคำค้นแบบนี้ได้ตามปกติ แต่ไม่ส่งเข้า URL —
 * ประวัติเบราว์เซอร์/ลิงก์ที่แชร์ไม่ควรมีเลขบัตรเต็ม (CLAUDE.md กฎ 7)
 */
export function looksLikeNationalId(q: string): boolean {
  return q.replace(/\D/g, "").length >= NATIONAL_ID_DIGITS;
}
