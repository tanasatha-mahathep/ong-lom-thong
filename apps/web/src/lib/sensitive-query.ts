import { normalizeNationalId } from "@ong/core";

/**
 * คำค้นที่เป็นเลขบัตรประชาชนเต็ม 13 หลัก (ไม่ตรวจ checksum — พิมพ์ผิดก็ยังเป็นรูปเลขบัตร ไม่ควรลง URL เหมือนกัน)
 * รับรูปที่คั่นด้วยช่องว่าง/ขีดตามหน้าบัตร ("1 1037 00123 45 8" · "1-1037-00123-45-8") ด้วย
 * หน้าค้นทุกหน้า (ค้นบิล · ค้นลูกค้า) ค้นด้วยเลขนี้ได้ตามปกติ แต่ไม่ส่งเข้า URL —
 * ประวัติเบราว์เซอร์/ลิงก์ที่แชร์ไม่ควรมีเลขบัตรเต็ม (CLAUDE.md กฎ 7)
 */
export function looksLikeNationalId(q: string): boolean {
  return /^\d{13}$/.test(normalizeNationalId(q));
}
