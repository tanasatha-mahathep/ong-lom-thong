import { describe, expect, it } from "vitest";
import { looksLikeNationalId } from "./sensitive-query";

describe("looksLikeNationalId", () => {
  it.each([
    ["13 หลักติดกัน", "1103700123458"],
    ["จัดกลุ่มแบบหน้าบัตร (ช่องว่าง)", "1 1037 00123 45 8"],
    ["ขีดคั่น ASCII", "1-1037-00123-45-8"],
    ["ขีดคั่นไม่ตัดบรรทัด U+2011", "1‑1037‑00123‑45‑8"],
    ["ขีด en dash U+2013", "1–1037–00123–45–8"],
    ["จุดคั่น", "1.1037.00123.45.8"],
    ["มีอักขระความกว้างศูนย์แทรก U+200B", "1103700​123458"],
    ["12 หลัก (หลักที่ 13 คือ check digit ของ 12 หลักแรก)", "110370012345"],
    ["14 หลัก (กดซ้ำ)", "11037001234581"],
    ["เลขบัตรตามด้วยชื่อ", "1103700123458 สมชาย"],
    ["คำนำหน้าเลขบัตร", "เลขบัตร 1103700123458"],
    ["12 หลักปนตัวอักษร", "110370012345x"],
  ])("%s → เป็นเลขบัตร", (_name, q) => {
    expect(looksLikeNationalId(q)).toBe(true);
  });

  it.each([
    ["ว่าง", ""],
    ["ชื่อ", "สมชาย"],
    ["เบอร์มือถือ 10 หลัก", "0812345678"],
    ["เบอร์มีขีด", "081-234-5678"],
    ["เบอร์รหัสประเทศ (11 หลัก)", "+66 81 234 5678"],
    ["เลขที่บิล", "RC6910-0001"],
    ["11 หลัก (ยังไม่ครบ 12)", "11037001234"],
    ["ตัวเลขไทย (API ไม่นับเป็นตัวเลข)", "๑๑๐๓๗๐๐๑๒๓๔๕๘"],
  ])("%s → ไม่ใช่เลขบัตร", (_name, q) => {
    expect(looksLikeNationalId(q)).toBe(false);
  });
});
